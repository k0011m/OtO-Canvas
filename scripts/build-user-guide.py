body = ParagraphStyle('body', fontName='JP', fontSize=12, leading=21, textColor=INK, wordWrap='CJK')
small = ParagraphStyle('small', parent=body, fontSize=10, leading=17)
y = 0

# 段落の高さを実測し、フッターへはみ出す内容は生成時に検出する。
def para(text, style=body, gap=14):
    global y
    p = Paragraph(text, style)
    _, height = p.wrap(W - 88, 1000)
    if y - height < 66:
        raise ValueError('ページの文章が多すぎます: ' + text[:30])
    p.drawOn(c, 44, y - height)
    y -= height + gap

# 全ページで見出しとページ番号をそろえ、印刷しても参照しやすくする。
def page(number, title, subtitle):
    global y
    if number > 1:
        c.showPage()
    c.setFillColor(HexColor('#fffdf8'))
    c.rect(0, 0, W, H, fill=1, stroke=0)
    c.setFillColor(TEAL)
    c.roundRect(44, H - 62, 34, 26, 9, fill=1, stroke=0)
    c.setFont('JPBold', 13)
    c.setFillColor(HexColor('#ffffff'))
    c.drawCentredString(61, H - 54, str(number).zfill(2))
    c.setFillColor(INK)
    c.setFont('JPBold', 11)
    c.drawString(90, H - 54, 'OtO Canvas  あそびかたガイド')
    c.setFont('JPBold', 25)
    c.drawString(44, H - 109, title)
    c.setFont('JP', 10)
    c.setFillColor(TEAL)
    c.drawString(44, H - 134, subtitle)
    c.setStrokeColor(HexColor('#dedbd3'))
    c.line(44, 48, W - 44, 48)
    c.setFont('JP', 9)
    c.setFillColor(INK)
    c.drawString(44, 31, 'Android・ブラウザ版共通 / ver 0.4.11')
    c.drawRightString(W - 44, 31, f'{number} / 6')
    y = H - 167

# 操作ごとの見出しを色で区切り、読む順番を分かりやすくする。
def section(title, text):
    global y
    c.setFont('JPBold', 14)
    c.setFillColor(TEAL)
    c.drawString(44, y - 14, title)
    y -= 28
    para(text)

